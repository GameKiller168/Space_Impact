#!/usr/bin/env python3
"""Generate web/js/spaceimpact-texts.js from the firmware's own text tables.

Two kinds of texts are written:

* labels and notes (New game, Continue, Top score, Instructions, the top-score and game-over notes) for the five
  languages of the PPM B image itself (English, German, French, Italian, Dutch). Their tables decode exactly
  (the length table, the one-byte gap and the section end agree), so they are taken as the phone shows them;
* the Space Impact instruction text, the last text of every language section, for the further languages whose section
  could be read back to a clean sentence (Hungarian, Lithuanian, Latvian, Turkish, Russian).

Other languages of the language packs have their tables in a layout this tool does not fully decode yet; the page then
shows the English firmware text for the instructions and its own estimated labels, and says so in FIDELITY.md.

Usage: python3 tools/spaceimpact_generate_texts.py --flash main.fls --ppm-dir DIR [--output web/js/spaceimpact-texts.js]
"""
import argparse, hashlib, json, re
from pathlib import Path
import spaceimpact_extract_texts as X

LABELS = ['NEW_GAME', 'CONTINUE', 'TOP_SCORE', 'INSTRUCTIONS', 'TOP_SCORE_NOTE', 'GAME_OVER_TOP', 'GAME_OVER_SCORE', 'YOU_WON']
MAIN = {'en': 'ENGL', 'de': 'GERM', 'fr': 'FREN', 'it': 'ITAL', 'nl': 'DUTC'}
# language -> (pack letter, section tag, text encoding of the section, bytes per length unit)
EXTRA = {'hu': ('N', 'HUNG', 'utf-8', 1), 'lt': ('L', 'LITH', 'utf-8', 1), 'lv': ('Y', 'LATV', 'utf-8', 1),
         'tr': ('O', 'TURK', 'utf-8', 1), 'ru': ('E', 'RUSS', 'utf-16-be', 2)}


def utf_instruction(path, tag, codec, unit):
    data = Path(path).read_bytes()
    found = X.sections(data)
    for i, (start, t, flag, size) in enumerate(found):
        if t != tag or not (flag & 0x80) or i + 1 >= len(found):
            continue
        tbl = start + 16
        n = next(k for k in range(1300, 1400) if data[tbl + k] == 0xff and data[tbl + k - 1] != 0xff)
        end = found[i + 1][0]
        while data[end - 1] == 0xff:
            end -= 1
        window = data[end - data[tbl + n - 1] * unit:end]
        text = window.decode(codec)
        # the length byte can count the full stop that ends the previous text; keep the sentence that starts the text
        match = re.search(r'^[^A-ZÀ-ɏЀ-Я]*\.(?=[A-ZÀ-ɏЀ-Я])', text)
        if match:
            text = text[match.end():]
        return text
    raise SystemExit('section %s not found' % tag)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--flash', required=True)
    parser.add_argument('--ppm-dir', required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent.parent / 'web/js/spaceimpact-texts.js')
    args = parser.parse_args()
    sections = {(s['pack'], s['tag']): s for s in X.extract(args.flash, 'MAIN', {})}
    labels, instructions = {}, {}
    for lang, tag in MAIN.items():
        s = sections[('MAIN', tag)]
        labels[lang] = {k: s[k] for k in LABELS}
        instructions[lang] = s['instruction']
    for lang, (pack, tag, codec, unit) in EXTRA.items():
        instructions[lang] = utf_instruction('%s/NHM5NY06.39%s' % (args.ppm_dir, pack), tag, codec, unit)
    sha = hashlib.sha256(Path(args.flash).read_bytes()).hexdigest()
    body = json.dumps({'labels': labels, 'instructions': instructions}, ensure_ascii=False, indent=2)
    js = """/* Space Impact texts, read from the text tables of the Nokia 3310 v6.39 firmware (PPM B image: %s).
 * Generated by tools/spaceimpact_generate_texts.py; do not edit by hand.
 *
 * labels:       New game, Continue, Top score, Instructions and the notes, as the phone shows them, for the five languages
 *               of the PPM B image (text ids 560, 552, 553, 554, 537, 576, 578, 579).
 * instructions: the Space Impact instruction text (id 1332, the last text of every language section) for the languages
 *               whose section reads back to a clean sentence. Other languages use the English text.
 */
(function (root) {
  'use strict';
  var ns = (root.SpaceImpact = root.SpaceImpact || {});
  var DATA = %s;

  function base(language) { return typeof language === 'string' ? language.toLowerCase().split(/[-_]/)[0] : 'en'; }
  function own(object, key) { return Object.prototype.hasOwnProperty.call(object, key); }

  ns.Texts = {
    // the instruction text for a language code, English when the firmware text of that language is not decoded
    instructions: function (language) { var code = base(language); return own(DATA.instructions, code) ? DATA.instructions[code] : DATA.instructions.en; },
    hasInstructions: function (language) { return own(DATA.instructions, base(language)); },
    // a label or note straight from the firmware, or null when the language is not one of the five decoded ones
    label: function (key, language) { var code = base(language); return own(DATA.labels, code) && own(DATA.labels[code], key) ? DATA.labels[code][key] : null; },
    hasLabels: function (language) { return own(DATA.labels, base(language)); },
    labelLanguages: Object.keys(DATA.labels), instructionLanguages: Object.keys(DATA.instructions)
  };
  if (typeof module === 'object' && module.exports) module.exports = ns.Texts;
})(typeof globalThis !== 'undefined' ? globalThis : this);
""" % (sha[:16] + '...', body.replace('\n', '\n  ').replace('\n  }', '\n  }'))
    args.output.write_text(js, encoding='utf-8')
    print(args.output)


if __name__ == '__main__':
    main()
